"""Check that the container hash lock is the frozen uv production resolution."""
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
result = subprocess.run([
    'uv', 'export', '--frozen', '--no-dev', '--no-emit-project',
    '--format', 'requirements-txt', '--no-header',
], cwd=ROOT, check=True, text=True, capture_output=True, timeout=60)
committed = (ROOT / 'requirements-runtime.lock').read_text(encoding='utf-8')
if not committed.startswith('# This file was autogenerated by uv'):
    raise RuntimeError('Unexpected runtime lock header')
payload = '\n'.join(committed.splitlines()[2:]).strip()
if result.stdout.strip() != payload:
    raise RuntimeError('Runtime hash lock differs from the frozen uv production resolution')
print('Runtime hash lock matches the frozen uv production resolution')
